export function bookIcon(id: string): ViewIcon {
  if (id === "map") return viewIcon("street");
  const grid = (BOOK[id] ?? BOOK.today).map((row) => row.slice(0, 11).replace(/[^.a-z]/g, "o"));
  return { grid, palette: PAL };
}

export function viewIcon(id: string): ViewIcon {
  const grid = (ICONS[id] ?? ICONS.room).map((row) => row.slice(0, 11).replace(/[A-Z0-9]/g, (c) => c.toLowerCase().replace("0", "o")));
  return { grid, palette: PAL };
}
