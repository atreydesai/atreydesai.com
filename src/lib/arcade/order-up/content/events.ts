/** What an effect does that the numbers don't say. */
const EFFECT_LEADS: Partial<Record<string, string>> = {
  delayed: "Scheduled deliveries come a day late.",
  "power-cut": "The machines are off, so work by hand.",
  melt: "Iced drinks melt faster at the pass.",
  hot: "Guests order hot drinks.",
};

/** An event's day in a sentence: what it does, then how busy, patient and generous guests are. */
function describe(event: Event) {
  const pct = (x: number) => Math.round(Math.abs(x - 1) * 100) + "%";
  const parts: string[] = [];
  if (event.arrival !== 1) parts.push(`${pct(event.arrival)} ${event.arrival > 1 ? "more" : "fewer"} guests come`);
  if (event.patience !== 1) parts.push(`they wait ${pct(event.patience)} ${event.patience > 1 ? "longer" : "less"}`);
  if (event.tips !== 1) parts.push(`tips are ${pct(event.tips)} ${event.tips > 1 ? "bigger" : "smaller"}`);
  if (event.price !== 1) parts.push(`stock costs ${pct(event.price)} ${event.price > 1 ? "more" : "less"}`);
  const numbers = parts.length
    ? parts.length <= 2
      ? parts.join(" and ")
      : parts.slice(0, -1).join(", ") + ", and " + parts[parts.length - 1]
    : "";
  const sentence = numbers ? numbers.charAt(0).toUpperCase() + numbers.slice(1) + "." : "";
  return [EFFECT_LEADS[event.effect], sentence].filter(Boolean).join(" ") || event.description;
}

