export type TreeArtifact = {
  id: TreeNodeId;
  output: string;
  kind: "material" | "capability";
  producer: TreeNodeId;
  consumers: readonly TreeNodeId[];
  /** End-of-graph consumers include service, upkeep and settlement. */
  terminalUse: string | null;
};

export const TREE_ARTIFACTS: readonly TreeArtifact[] = TREE_NODES.map((node) => {
  const consumers = TREE_NODES.filter((next) => next.requires.includes(node.id)).map((next) => next.id);
  return {
    id: node.id,
    output: node.product,
    kind: SPENT_OUTPUTS.includes(node.id) ? "material" : "capability",
    producer: node.id,
    consumers,
    terminalUse: SERVICE_OUTPUTS[node.id] ?? null,
  };
});
