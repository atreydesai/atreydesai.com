const groupFor = (id: string): Ingredient["group"] =>
  ["black", "jasmine", "taro"].includes(id)
    ? "tea"
    : ["milk", "oat"].includes(id)
      ? "milk"
      : ["strawberry", "banana", "mango", "yuzu"].includes(id)
        ? "fruit"
        : ["bun", "waffle"].includes(id)
          ? "side"
          : ["brown-sugar", "honey", "vanilla", "sesame-syrup"].includes(id)
            ? "syrup"
            : ["seltzer", "banana-scoop", "vanilla-scoop"].includes(id)
              ? "finish"
              : "topping";
