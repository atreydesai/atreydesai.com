import type { Machine } from "./schema.ts";

/**
 * The workshop's machines. Every machine comes in the same three tiers,
 * enamel, steel and brass, each better, faster and holding more; only
 * their seeds and first colour differ, so the tiers are made here.
 */
const TIERS = [
  { name: "enamel", grade: 88, speed: 1, capacity: 1, color: "" },
  { name: "steel", grade: 93, speed: 1.25, capacity: 2, color: "#b1b7ab" },
  { name: "brass", grade: 97, speed: 1.55, capacity: 3, color: "#d0b17b" },
] as const;

function tiers(
  motif: string,
  first: string,
  seeds: readonly number[],
): Machine["tiers"] {
  return TIERS.map((t, i) => ({
    name: t.name,
    grade: t.grade,
    speed: t.speed,
    capacity: t.capacity,
    art: { kind: "machine", color: t.color || first, motif, seed: seeds[i] },
  }));
}

