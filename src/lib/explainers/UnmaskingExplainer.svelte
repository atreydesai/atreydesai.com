<script lang="ts" module>
	// Frontier models need only one text to unmask its human or AI author
	// (Desai, Bölöni-Turgut, Brassington, Choi, Russell, Rajendhran, et al. 2026)
	//
	// Beats: one anonymous text, "who wrote this?" -> level 1, AI or human ->
	// level 2, which lab -> level 3, which human.
	//
	// Every claim and number is the abstract's (captions condense its
	// wording): "a single text and a simple
	// zero-shot prompt (no web access, tools, candidate lists, or writing
	// samples)"; the latest models "match trained detectors like Pangram while
	// also explaining their predictions in natural language"; "Opus 5.5 names
	// the correct lab for 98% of texts generated by models from Anthropic,
	// OpenAI, and Google"; "Fable 5.2 correctly names the human reviewer of
	// 56% of 398 private peer reviews written by our lab"; "(3) if a human, often exactly
	// who". The texts are placeholder ink, the AI verdict and the lab it lands
	// on (LAB_PICK) are illustrative, and the reviewer's name is drawn as ink,
	// never written: no real person is shown.
	import type { Beat } from "./motion";

	const BEATS: Beat[] = [
		{ id: "text", label: "one text", at: 0 },
		{ id: "ai", label: "AI or human", at: 2.6 },
		{ id: "lab", label: "which lab", at: 6.6 },
		{ id: "human", label: "which human", at: 10.6, hold: 13.8 },
	];
	const DURATION = 15;

	// The text: lines of ink under the title. The AI-written one (beats 1-3)
	// runs four lines; the human-written review (beat 4) is a different text,
	// three lines, so its label clears the stat beside the byline.
	const INK_Y = [42, 56, 70, 84];
	const INK_H = 8;
	const AI_TEXT = [212, 196, 208, 132];
	const HUMAN_TEXT = [204, 212, 118];
	const DOC_LABEL_Y = 96;

	// The byline: a person glyph with a name slot beside it, on one baseline.
	const BY = 150;
	const NAME_X = 44;
	const NAME = [30, 40];
	const NAME_GAP = 5;
	const NAME_W = NAME[0] + NAME_GAP + NAME[1];

	// Level 1: two rows, the verdict on the first.
	const OPTIONS = [
		{ text: "AI", y: 132, ink: "--xp-accent-text" },
		{ text: "human", y: 160, ink: "--xp-human" },
	];
	const OPT_RULE = 8;
	const LEFT_X2 = 112;

	// The model's explanation: three lines of its ink in a speech bubble that
	// points at the verdict.
	const SAY = [
		{ y: 119, w: 80 },
		{ y: 133, w: 74 },
		{ y: 147, w: 46 },
	];
	const SAY_X = 136;

	// Level 2: three labs, one row each; the stat stands to their right.
	const LABS = [
		{ name: "Anthropic", y: 126 },
		{ name: "OpenAI", y: 151 },
		{ name: "Google", y: 176 },
	];
	const LAB_RULE = 7;
	const LAB_X2 = 130;
	const LAB_PICK = 1;

	// Hero number and its two labels, right-aligned, in beats 3 and 4.
	const STAT_Y = 146;
</script>

<script lang="ts">
	import ExplainerFrame from "./ExplainerFrame.svelte";
	import { T, draw, enter, exit, restore, swap, write, type ExplainerProps, type Scene } from "./motion";

	let { size = "card", paused = false, resting = false, label }: ExplainerProps = $props();

	const uid = $props.id();
	const lab = LABS[LAB_PICK];
	const labAbove = LABS[LAB_PICK - 1];
	// The text's ink: neutral until the verdict, then the AI's colour as --ai
	// runs 0% -> 100%. Theme-safe, since both ends stay variables.
	const AI_INK = "fill: color-mix(in srgb, var(--xp-accent) var(--ai, 0%), var(--xp-faint))";
	const check = (x: number, y: number) => `M${x} ${y - 6} l5 5 l9 -11`;

	const scene: Scene = {
		beats: BEATS,
		duration: DURATION,
		build(tl, root) {
			const sayWipes = [...root.querySelectorAll(".u-wipe-say")];
			const nameWipe = root.querySelector(".u-wipe-name");
			const poster = [".u-head-q", ".u-doc", ".u-anon", ".u-blank", ".u-cap-q"];
			const lit = (sel: string, at: number) =>
				tl.fromTo(sel, { autoAlpha: 0 }, { autoAlpha: 1, duration: 0.35, ease: "power2.out", immediateRender: false }, at);

			// 2 · AI or human: the verdict lands on AI, the text takes the
			// AI's ink, and the model says why.
			swap(tl, ".u-head-q", ".u-head-1", 2.6);
			exit(tl, [".u-anon", ".u-blank", ".u-cap-q"], 2.6);
			enter(tl, ".u-opt", 2.9, { stagger: 0.15 });
			const verdict = 3.7;
			lit(".u-hl-ai", verdict);
			tl.to(".u-dim-opt", { opacity: 0.35, duration: 0.4, ease: "power2.out" }, verdict);
			tl.fromTo(".u-doc", { "--ai": "0%" }, { "--ai": "100%", duration: 0.5, ease: "power2.out", immediateRender: false }, verdict);
			tl.set(".u-check-ai", { autoAlpha: 1 }, verdict + 0.2);
			draw(tl, ".u-check-ai", verdict + 0.2, 0.35);
			enter(tl, ".u-bubble", 4.3);
			tl.set(".u-say", { autoAlpha: 1 }, 4.55);
			sayWipes.forEach((wipe, i) => write(tl, wipe, SAY[i].w, 4.55 + i * 0.3, 0.35));
			enter(tl, ".u-cap-1", 5.4);

			// 3 · which lab: three labs, one picked; Opus 5.5's 98%.
			exit(tl, [".u-opt", ".u-hl-ai", ".u-check-ai", ".u-bubble", ".u-say", ".u-cap-1"], "lab");
			swap(tl, ".u-head-1", ".u-head-2", 6.6);
			enter(tl, ".u-lab", 6.9, { stagger: 0.15 });
			const pick = 7.9;
			lit(".u-hl-lab", pick);
			tl.to(".u-dim-lab", { opacity: 0.35, duration: 0.4, ease: "power2.out" }, pick);
			tl.set(".u-check-lab", { autoAlpha: 1 }, pick + 0.2);
			draw(tl, ".u-check-lab", pick + 0.2, 0.35);
			enter(tl, ".u-stat-lab", 8.45, { stagger: 0.1 });
			enter(tl, ".u-cap-2", 8.95);

			// 4 · which human: a human-written review this time. The anonymous
			// byline comes back, then is unmasked: a person, a name, a check.
			exit(tl, [".u-doc", ".u-lab", ".u-hl-lab", ".u-check-lab", ".u-stat-lab", ".u-cap-2"], "human");
			swap(tl, ".u-head-2", ".u-head-3", 10.6);
			enter(tl, ".u-doc-h", 10.9);
			enter(tl, ".u-doc-label", 11.1);
			enter(tl, [".u-anon", ".u-alias"], 11.4);
			const unmask = 12.2;
			exit(tl, [".u-anon", ".u-alias"], unmask, { duration: 0.25 });
			enter(tl, ".u-who", unmask + 0.25);
			tl.set(".u-name", { autoAlpha: 1 }, unmask + 0.3);
			write(tl, nameWipe, NAME_W + 1, unmask + 0.3, 0.45);
			tl.set(".u-check-who", { autoAlpha: 1 }, unmask + 0.65);
			draw(tl, ".u-check-who", unmask + 0.65, 0.35);
			enter(tl, ".u-stat-who", 12.85, { stagger: 0.1 });
			enter(tl, ".u-cap-3", 13.25);

			// Back to the poster: reset what changed while it is hidden, then
			// bring the poster back, ending by 14.8.
			exit(tl, [".u-head-3", ".u-doc-h", ".u-doc-label", ".u-who", ".u-name", ".u-check-who", ".u-stat-who", ".u-cap-3"], 14.0);
			tl.set(".u-doc", { "--ai": "0%" }, 14.3);
			tl.set(".u-dim", { opacity: 1 }, 14.3);
			tl.set([...sayWipes, nameWipe], { attr: { width: 0 } }, 14.3);
			restore(tl, poster, 14.35);
		},
	};
</script>

<ExplainerFrame {scene} {label} {size} {paused} {resting}>
	<defs>
		<clipPath id="{uid}-say">
			{#each SAY as line}
				<rect class="u-wipe-say" x={SAY_X} y={line.y - 1} width="0" height={INK_H} />
			{/each}
		</clipPath>
		<clipPath id="{uid}-name">
			<rect class="u-wipe-name" x={NAME_X} y={BY - 18} width="0" height="18" />
		</clipPath>
	</defs>

	<!-- The question at each level, as the plate's title. -->
	<text class="xp-prose u-head-q" x="14" y="30" font-size={T.head}>Who wrote this?</text>
	<text class="xp-prose xp-later u-head-1" x="14" y="30" font-size={T.head}>AI or human?</text>
	<text class="xp-prose xp-later u-head-2" x="14" y="30" font-size={T.head}>Which lab?</text>
	<text class="xp-prose xp-later u-head-3" x="14" y="30" font-size={T.head}>Which human?</text>

	<!-- 1 · poster: one anonymous text -->
	<g class="u-doc">
		{#each AI_TEXT as w, i}
			<rect x="14" y={INK_Y[i]} width={w} height={INK_H} rx="2" fill-opacity="0.55" style={AI_INK} />
		{/each}
	</g>
	<g class="u-anon" fill="none" stroke="var(--xp-soft)" stroke-width="1.4" stroke-dasharray="2.6 2.2">
		<circle cx="24" cy={BY - 18} r="5.5" />
		<path d="M13 {BY} a11 11 0 0 1 22 0 Z" />
	</g>
	<line class="u-blank" x1={NAME_X} x2="150" y1={BY - 2} y2={BY - 2} stroke="var(--xp-faint)" stroke-width="1.4" stroke-dasharray="4 3.5" />
	<text class="xp-prose xp-caption u-cap-q" style="color: var(--xp-accent-text)"><tspan x="14" y="205">only one text,</tspan><tspan x="14" y="226">no writing samples</tspan></text>

	<!-- 2 · AI or human -->
	<rect class="xp-later u-hl-ai" x="14" y={OPTIONS[0].y - 19} width={LEFT_X2 - 14} height="26" rx="2" fill="var(--xp-truth)" fill-opacity="0.1" />
	{#each OPTIONS as opt, i}
		<!-- Outer groups fade in and out; inner ones dim. -->
		<g class="xp-later u-opt">
			<g class={i === 0 ? undefined : "u-dim u-dim-opt"}>
				<text class="xp-prose" x="14" y={opt.y} font-size={T.body} style="color: var({opt.ink})">{opt.text}</text>
				<line class="xp-rule" x1="14" x2={LEFT_X2} y1={opt.y + OPT_RULE} y2={opt.y + OPT_RULE} />
			</g>
		</g>
	{/each}
	<path class="xp-later u-check-ai" d={check(92, OPTIONS[0].y)} fill="none" stroke="var(--xp-truth)" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" />
	<path
		class="xp-later u-bubble"
		d="M132 108 H220 a6 6 0 0 1 6 6 V162 a6 6 0 0 1 -6 6 H132 a6 6 0 0 1 -6 -6 V134 L118 127 L126 122 V114 a6 6 0 0 1 6 -6 Z"
		fill="var(--xp-surface)"
		stroke="var(--xp-accent)"
		stroke-width="1.3"
		stroke-linejoin="round"
	/>
	<g class="xp-later u-say" clip-path="url(#{uid}-say)">
		{#each SAY as line}
			<rect x={SAY_X} y={line.y} width={line.w} height="7" rx="2" fill="var(--xp-accent)" fill-opacity="0.55" />
		{/each}
	</g>
	<text class="xp-prose xp-caption xp-later u-cap-1" style="color: var(--xp-accent-text)"><tspan x="14" y="205">matches Pangram,</tspan><tspan x="14" y="226">and explains why</tspan></text>

	<!-- 3 · which lab -->
	<rect class="xp-later u-hl-lab" x="14" y={labAbove.y + LAB_RULE} width={LAB_X2 - 14} height={lab.y - labAbove.y} fill="var(--xp-truth)" fill-opacity="0.1" />
	{#each LABS as row, i}
		<g class="xp-later u-lab">
			<g class={i === LAB_PICK ? undefined : "u-dim u-dim-lab"}>
				<text class="xp-prose" x="14" y={row.y} font-size={T.stem}>{row.name}</text>
				<line class="xp-rule" x1="14" x2={LAB_X2} y1={row.y + LAB_RULE} y2={row.y + LAB_RULE} />
			</g>
		</g>
	{/each}
	<path class="xp-later u-check-lab" d={check(112, lab.y)} fill="none" stroke="var(--xp-truth)" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" />
	<text class="xp-display xp-later u-stat-lab" x="226" y={STAT_Y} font-size={T.hero} text-anchor="end" style="color: var(--xp-accent-text)">98%</text>
	<text class="xp-mono xp-later u-stat-lab" x="226" y={STAT_Y + 18} font-size={T.label} text-anchor="end">of texts</text>
	<text class="xp-mono xp-later u-stat-lab" x="226" y={STAT_Y + 34} font-size={T.label} text-anchor="end" style="color: var(--xp-accent-text)">Opus 5.5</text>
	<text class="xp-prose xp-caption xp-later u-cap-2" x="14" y="214" style="color: var(--xp-accent-text)">names the correct lab</text>

	<!-- 4 · which human: an anonymous review, unmasked -->
	<g class="xp-later u-doc-h">
		{#each HUMAN_TEXT as w, i}
			<rect x="14" y={INK_Y[i]} width={w} height={INK_H} rx="2" fill="var(--xp-human)" fill-opacity="0.55" />
		{/each}
	</g>
	<text class="xp-mono xp-later u-doc-label" x="14" y={DOC_LABEL_Y} font-size={T.label}>private peer review</text>
	<text class="xp-mono xp-later u-alias" x={NAME_X} y={BY - 4} font-size="14">Reviewer #2</text>
	<g class="xp-later u-who" fill="var(--xp-human)">
		<circle cx="24" cy={BY - 18} r="5.5" />
		<path d="M13 {BY} a11 11 0 0 1 22 0 Z" />
	</g>
	<g class="xp-later u-name" clip-path="url(#{uid}-name)">
		<rect x={NAME_X} y={BY - 14} width={NAME[0]} height="10" rx="2" fill="var(--xp-human)" />
		<rect x={NAME_X + NAME[0] + NAME_GAP} y={BY - 14} width={NAME[1]} height="10" rx="2" fill="var(--xp-human)" />
	</g>
	<path class="xp-later u-check-who" d={check(NAME_X + NAME_W + 8, BY - 4)} fill="none" stroke="var(--xp-truth)" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" />
	<text class="xp-display xp-later u-stat-who" x="226" y={STAT_Y} font-size={T.hero} text-anchor="end" style="color: var(--xp-accent-text)">56%</text>
	<text class="xp-mono xp-later u-stat-who" x="226" y={STAT_Y + 18} font-size={T.label} text-anchor="end">of 398 reviews</text>
	<text class="xp-mono xp-later u-stat-who" x="226" y={STAT_Y + 34} font-size={T.label} text-anchor="end" style="color: var(--xp-accent-text)">Fable 5.2</text>
	<text class="xp-prose xp-caption xp-later u-cap-3" style="color: var(--xp-accent-text)"><tspan x="14" y="205">if a human, often</tspan><tspan x="14" y="226">exactly who</tspan></text>
</ExplainerFrame>
