// Precomputes the header's a -> A and d -> D shape morphs, so the page can play
// them without GSAP. MorphSVG's work at runtime was to rewrite each pair of
// outlines into the same number of cubic segments (and pick the best starting
// point, shapeIndex "auto"); after that a morph is just interpolating numbers.
// That rewrite depends only on the outlines, so it is done here, once, with the
// same MorphSVG settings the header used, and written to
// src/lib/wordmark-morph.ts. Re-run after changing src/lib/wordmark.ts:
//
//   node scripts/wordmark-morph.mjs
//
// tests/wordmark-morph.test.mjs fails if the file is stale.

import { writeFileSync } from "node:fs";
import { gsap } from "gsap";
import { MorphSVGPlugin } from "gsap/MorphSVGPlugin";
import { MONOGRAM_A, MONOGRAM_D, WORDMARK_LETTERS, WORDMARK_SPLIT } from "../src/lib/wordmark.ts";

gsap.registerPlugin(MorphSVGPlugin);

/** The header's morph settings: shapeIndex "auto", MorphSVG's default map. */
export function morphPair(from, to) {
  const [start, end] = MorphSVGPlugin.normalizeStrings(from, to, { shapeIndex: "auto", map: "size" });
  return [start, end];
}

export function morphSource() {
  const a = morphPair(WORDMARK_LETTERS[0], MONOGRAM_A);
  const d = morphPair(WORDMARK_LETTERS[WORDMARK_SPLIT], MONOGRAM_D);
  return `// Generated by scripts/wordmark-morph.mjs from src/lib/wordmark.ts; do not edit.
// Each pair is a letter and its monogram capital rewritten into the same
// cubic segments, so the header morphs one into the other by interpolating
// the numbers (see Header.svelte).

export const MORPH_A: readonly [string, string] = ${JSON.stringify(a)};
export const MORPH_D: readonly [string, string] = ${JSON.stringify(d)};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("../src/lib/wordmark-morph.ts", import.meta.url), morphSource());
  console.log("wrote src/lib/wordmark-morph.ts");
}
